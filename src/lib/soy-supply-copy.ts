/** Percent with enough decimals that a tiny share doesn't read as 0%. */
export function formatSharePct(p: number, lang: Lang): string {
  const loc = lang === "id" ? "id-ID" : "en-US";
  if (p === 0) return "0%";
  // Small shares and shares just under 100% both need decimals: 0.022% and
  // 99.978% (never a rounded "100%" next to a non-zero non-compliant share).
  const digits = p < 0.1 || p > 99.9 ? 3 : p < 1 || p > 99 ? 2 : 1;
  const text = p.toLocaleString(loc, { maximumFractionDigits: digits });
  if (p < 100 && Number(p.toFixed(digits)) >= 100) return `> ${(99.999).toLocaleString(loc)}%`;
  return `${text}%`;
}
